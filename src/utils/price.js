// Цена товара в том виде, в каком её показываем покупателю.
//
// Покупатель платит по `price`. Если у товара заполнена `old_price` и она
// больше нынешней — товар уценён, и старую цену показываем зачёркнутой
// рядом. Процент скидки нигде не пишем: так решено.

export const formatPrice = (значение) =>
  `${Math.round(Number(значение) || 0).toLocaleString('ru-RU')} KZT`;

export const hasDiscount = (товар) =>
  Number(товар?.old_price) > Number(товар?.price);
